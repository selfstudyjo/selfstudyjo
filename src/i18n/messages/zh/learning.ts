/**
 * Courses, homework, exams, quizzes, certificates, the leaderboard, runbooks,
 * the labs, and both proctor screens — Chinese (Simplified).
 *
 * Three distinctions this file keeps that English collapses:
 *
 *  - **Exam vs quiz.** 考试 for the invigilated exam with a proctor and a
 *    certificate, 小测 for the quiz inside a lesson. Using 测验 for both leaves
 *    a student unable to tell which one they can retake from the course page.
 *  - **Measure words.** 门 for a course, 道 for a question, 节 for a lesson,
 *    张 for a certificate, 位 for a person, 台 for a device. English has none
 *    of these and 个 for all of them is the clearest sign of a translation
 *    nobody read back.
 *  - **The commands in the labs are not translated.** `ls -la` is `ls -la` in
 *    every language, and a student who copies a translated command gets one
 *    that does not run. Only the prose around them is Chinese — the same
 *    decision `rtl.css` makes in CSS for `<pre>` and `<code>`.
 */

