<template>
  <PgDialog v-model="tab" title="Create - Index" icon="index" :tabs="['General', 'Definition', 'SQL']" :error="error" :busy="busy"
            :save-disabled="!!problem" @close="$emit('close')" @save="save" @reset="reset" @clear-error="error = ''" @info="info" @help="help">
    <div v-show="tab === 'General'" class="pg-form">
      <div class="pg-row"><label class="pg-row__label" for="ci-name">Name</label>
        <input id="ci-name" v-model="spec.name" class="pg-input" autocomplete="off" placeholder="(generated by PostgreSQL when empty)" /></div>
      <div class="pg-row"><label class="pg-row__label is-req" for="ci-table">Table</label>
        <select id="ci-table" v-model="spec.table" class="pg-select" :disabled="Boolean(fixedTable)" @change="spec.columns = []; spec.include = []">
          <option value="">Select an item...</option>
          <option v-for="t in model.tables" :key="t.name" :value="t.name">public.{{ t.name }}</option>
        </select></div>
      <div class="pg-row"><span class="pg-row__label">Tablespace</span><select class="pg-select" disabled aria-label="Tablespace"><option>pg_default</option></select></div>
      <p class="pg-row__hint">Leave the name empty and PostgreSQL generates one (<code>{{ spec.table || 'table' }}_{{ spec.columns[0]?.column || 'column' }}_idx</code>).</p>
    </div>

    <div v-show="tab === 'Definition'" class="pg-form">
      <div class="pg-row"><label class="pg-row__label" for="ci-method">Access Method</label>
        <select id="ci-method" v-model="spec.method" class="pg-select"><option v-for="m in METHODS" :key="m" :value="m">{{ m }}</option></select></div>
      <div class="pg-row"><span class="pg-row__label">Unique?</span><PgSwitch v-model="spec.unique" label="Unique?" :disabled="spec.method !== 'btree'" /></div>
      <div class="pg-row"><span class="pg-row__label">Concurrent build?</span><PgSwitch v-model="spec.concurrently" label="Concurrent build?" /></div>
      <div class="pg-row"><label class="pg-row__label" for="ci-ff">Fill factor</label>
        <input id="ci-ff" v-model="spec.fillfactor" class="pg-input" inputmode="numeric" placeholder="10 - 100" /></div>
      <div class="pg-row pg-row--top"><span class="pg-row__label">Include columns</span>
        <div class="pg-form">
          <div class="pg-chips">
            <span v-for="c in spec.include" :key="c" class="pg-chip">{{ c }}<button type="button" :aria-label="'Remove ' + c" @click="spec.include = spec.include.filter(x => x !== c)">×</button></span>
          </div>
          <select class="pg-select" aria-label="Add include column" :disabled="spec.method !== 'btree' || !tableCols.length" @change="addInclude">
            <option value="">Select an item...</option>
            <option v-for="c in tableCols.filter(x => !spec.include.includes(x))" :key="c" :value="c">{{ c }}</option>
          </select>
        </div></div>
      <div class="pg-row pg-row--top"><label class="pg-row__label" for="ci-where">Constraint</label>
        <textarea id="ci-where" v-model="spec.where" class="pg-textarea pg-mono" rows="2" placeholder="status = 'paid'  (a partial index)" /></div>

      <div class="pg-dgrid__add"><h3 class="pg-sub">Columns</h3>
        <button type="button" class="pg-btn pg-btn--sm" :disabled="!spec.table" @click="spec.columns.push({ column: '', order: 'ASC', nulls: 'LAST' })"><PgIcon name="plus" :size="13" />Add row</button></div>
      <div class="pg-dgrid__wrap">
        <table class="pg-dgrid">
          <thead><tr><th></th><th>Column</th><th>Sort order</th><th>NULLs</th></tr></thead>
          <tbody>
            <tr v-if="!spec.columns.length"><td colspan="4" class="pg-muted">No rows found</td></tr>
            <tr v-for="(c, i) in spec.columns" :key="i">
              <td><button type="button" class="pg-btn pg-btn--icon pg-btn--sm" :aria-label="'Delete index column ' + (i + 1)" @click="spec.columns.splice(i, 1)"><PgIcon name="trash" :size="13" /></button></td>
              <td><select v-model="c.column" class="pg-select" :aria-label="'Index column ' + (i + 1)"><option value="">Select an item...</option><option v-for="col in tableCols" :key="col" :value="col">{{ col }}</option></select></td>
              <td><select v-model="c.order" class="pg-select" :disabled="spec.method !== 'btree'" aria-label="Sort order" @change="c.nulls = c.order === 'ASC' ? 'LAST' : 'FIRST'"><option>ASC</option><option>DESC</option></select></td>
              <td><select v-model="c.nulls" class="pg-select" :disabled="spec.method !== 'btree'" aria-label="NULLs"><option>FIRST</option><option>LAST</option></select></td>
            </tr>
          </tbody>
        </table>
      </div>
    </div>

    <PgCode v-if="tab === 'SQL'" :sql="problem ? '-- ' + problem : generated" />
  </PgDialog>
</template>

<script setup lang="ts">
/**
 * Create - Index: name, access method, Unique?, Concurrent build?, INCLUDE
 * (covering) columns, a WHERE constraint (partial index), fill factor and the
 * column list with sort order and NULLs placement; Save runs the SQL tab.
 */
import { computed, inject, reactive, ref } from 'vue';
import PgDialog from './PgDialog.vue';
import PgIcon from './PgIcon.vue';
import PgSwitch from './PgSwitch.vue';
import PgCode from './PgCode.vue';
import { PG } from './pgContext';
import { createIndexSql, type IndexSpec } from './pg';

const props = defineProps<{ fixedTable?: string }>();
const emit = defineEmits<{ (event: 'close'): void }>();
const ctx = inject(PG)!;
const model = ctx.model;
const METHODS = ['btree', 'hash', 'gist', 'gin', 'brin', 'spgist'];

const tab = ref('General');
const error = ref('');
const busy = ref(false);

function blank(): IndexSpec {
  return { name: '', schema: 'public', table: props.fixedTable || '', method: 'btree', unique: false, concurrently: false,
    columns: [], include: [], where: '', fillfactor: '', comment: '' };
}
const spec = reactive<IndexSpec>(blank());
function reset() {
  Object.assign(spec, blank());
  error.value = '';
}

const tableCols = computed(() => ctx.table(spec.table)?.columns.map(c => c.name) || []);
function addInclude(event: Event) {
  const el = event.target as HTMLSelectElement;
  if (el.value && !spec.include.includes(el.value)) spec.include = [...spec.include, el.value];
  el.value = '';
}

const problem = computed(() => {
  if (!spec.table) return 'Please select the table.';
  if (!spec.columns.some(c => c.column)) return 'Please specify columns.';
  if (spec.name.trim() && model.value.indexes.some(i => i.name === spec.name.trim())) return `Index "${spec.name.trim()}" already exists.`;
  if (spec.fillfactor.trim() && !/^([1-9]\d|100)$/.test(spec.fillfactor.trim())) return 'Fill factor must be between 10 and 100.';
  if (spec.include.some(c => spec.columns.some(x => x.column === c))) return 'An include column cannot also be an index key column.';
  return '';
});
const generated = computed(() => createIndexSql(spec));

function info() {
  ctx.notify('info', 'Create - Index', 'Save runs the CREATE INDEX statement on the SQL tab; re-run EXPLAIN afterwards to see whether the planner uses it.');
}
function help() {
  ctx.notify('info', 'pgAdmin documentation: index_dialog.html', 'This lab is offline; the fields follow the PostgreSQL CREATE INDEX reference.');
}

async function save() {
  if (problem.value) {
    error.value = problem.value;
    return;
  }
  busy.value = true;
  const label = spec.name.trim() ? `Index "${spec.name.trim()}" created.` : `Index created on ${spec.table}.`;
  const result = await ctx.runSql(generated.value, { quiet: true, success: label });
  busy.value = false;
  if (result.ok) emit('close');
  else error.value = String(result.error || result.output || 'The index could not be created.').trim();
}
</script>

