<template>
  <div v-if="creating" class="cs-wizard">
    <ol class="cs-steps">
      <li v-for="(label, i) in steps" :key="label" :class="{ 'is-current': step === i, 'is-done': step > i }">Step {{ i + 1 }}<strong>{{ label }}</strong></li>
    </ol>
    <div>
      <template v-if="step === 0">
        <CsHeader title="Specify user details" />
        <section class="cs-container">
          <div class="cs-container__head"><CsHeader title="User details" :level="2" :info="false" /></div>
          <div class="cs-container__body cs-stack">
            <div class="cs-field"><label class="cs-label" for="iu-name">User name</label>
              <input id="iu-name" v-model.trim="name" class="cs-input" :class="{ 'is-invalid': tried && nameError }" />
              <span v-if="tried && nameError" class="cs-error-text">{{ nameError }}</span>
              <span class="cs-constraint">The user name can have up to 64 characters. Valid characters: A-Z, a-z, 0-9, and + = , . @ _ - (hyphen)</span></div>
            <label class="cs-check"><input type="checkbox" disabled /><span>Provide user access to the AWS Management Console - <em>optional</em>
              <small>If you're providing console access to a person, it's a best practice to manage their access in IAM Identity Center.</small></span></label>
          </div>
        </section>
      </template>
      <template v-else-if="step === 1">
        <CsHeader title="Set permissions" description="Add user to an existing group or create a new one. Using groups is a best-practice way to manage user's permissions by job functions." />
        <section class="cs-container">
          <div class="cs-container__head"><CsHeader title="Permissions options" :level="2" /></div>
          <div class="cs-container__body">
            <div class="cs-tiles">
              <label class="cs-tile iu__off"><input type="radio" disabled /><span><strong>Add user to group</strong><small>Add user to an existing group, or create a new group.</small></span></label>
              <label class="cs-tile iu__off"><input type="radio" disabled /><span><strong>Copy permissions</strong><small>Copy all group memberships, attached managed policies, and inline policies from an existing user.</small></span></label>
              <label class="cs-tile is-checked"><input type="radio" checked /><span><strong>Attach policies directly</strong><small>Attach a managed policy directly to a user.</small></span></label>
            </div>
          </div>
        </section>
        <PolicyPicker v-model="policies" description="Choose one or more policies to attach to your new user." />
      </template>
      <template v-else>
        <CsHeader title="Review and create" description="Review your choices. After you create the user, you can view and download the autogenerated password, if enabled." />
        <section class="cs-container">
          <div class="cs-container__head"><CsHeader title="User details" :level="2" :info="false" /></div>
          <div class="cs-container__body"><dl class="cs-kv"><div><dt>User name</dt><dd>{{ name }}</dd></div>
            <div><dt>Console password type</dt><dd>None</dd></div><div><dt>Require password reset</dt><dd>No</dd></div></dl></div>
        </section>
        <section class="cs-container">
          <div class="cs-container__head"><CsHeader :title="`Permissions summary (${policies.length})`" :level="2" :info="false" /></div>
          <div class="cs-container__body">
            <table class="cs-table-mini"><thead><tr><th>Name</th><th>Type</th><th>Used as</th></tr></thead>
              <tbody><tr v-for="arn in policies" :key="arn"><td>{{ arn.split('/').pop() }}</td><td>AWS managed</td><td>Permissions policy</td></tr>
                <tr v-if="!policies.length"><td colspan="3" class="cs-muted">No resources</td></tr></tbody></table>
          </div>
        </section>
        <section class="cs-container">
          <div class="cs-container__head"><CsHeader title="Tags - optional" :level="2" description="Tags are key-value pairs you can add to AWS resources to help identify, organize, or search for resources." /></div>
          <div class="cs-container__body"><TagEditor v-model="tags" /></div>
        </section>
      </template>
      <div class="cs-form-actions">
        <button type="button" class="cs-btn cs-btn--link" @click="ctx.to('iam', 'users')">Cancel</button>
        <button v-if="step > 0" type="button" class="cs-btn" @click="step--">Previous</button>
        <button v-if="step < 2" type="button" class="cs-btn cs-btn--primary" @click="next">Next</button>
        <button v-else type="button" class="cs-btn cs-btn--primary" :disabled="busy || tags.some(t => tagProblem(t))" @click="create">Create user</button>
      </div>
    </div>
  </div>

  <div v-else>
    <CsTable v-model:selected="selected" title="Users" variant="full-page" :items="users" :columns="columns" track-by="name"
             selection-type="multi" filter-placeholder="Search" empty-title="No resources to display"
             description="An IAM user is an identity with long-term credentials that is used to interact with AWS in an account.">
      <template #actions>
        <button type="button" class="cs-btn cs-btn--icon" aria-label="Refresh" @click="ctx.api.notify('info', 'Users refreshed')"><CsIcon name="refresh" /></button>
        <button type="button" class="cs-btn" :disabled="!selected.length" @click="deleting = true">Delete</button>
        <button type="button" class="cs-btn cs-btn--primary" @click="ctx.to('iam', 'user-create')">Create user</button>
      </template>
      <template #cell-name="{ row }"><a href="#" class="cs-link" @click.prevent="ctx.to('iam', 'user', { name: row.name })">{{ row.name }}</a></template>
    </CsTable>
    <CsDelete v-if="deleting" :title="selected.length === 1 ? `Delete ${selected[0]}?` : `Delete ${selected.length} users?`"
              :word="selected.length === 1 ? selected[0] : 'confirm'" :busy="busy" @close="deleting = false" @confirm="remove">
      <p class="iu__p">Permanently delete the selected user{{ selected.length > 1 ? 's' : '' }}? This action can't be undone. Attached policies are detached first.</p>
    </CsDelete>
  </div>
</template>

<script setup lang="ts">
import { computed, ref } from 'vue';
import { cli, rows } from '@/utils/portalKit';
import CsDelete from '../CsDelete.vue';
import CsHeader from '../CsHeader.vue';
import CsIcon from '../CsIcon.vue';
import CsTable, { type Column } from '../CsTable.vue';
import TagEditor, { type Tag } from '../TagEditor.vue';
import { tagProblem, tagWords } from '../commands';
import { awsDate, useAws } from '../ctx';
import PolicyPicker from './PolicyPicker.vue';

const ctx = useAws();
const creating = computed(() => ctx.route.value.page === 'user-create');
const users = computed(() => rows(ctx.view.value, 'iam.users'));
const selected = ref<string[]>([]);
const deleting = ref(false);
const busy = ref(false);
const steps = ['Specify user details', 'Set permissions', 'Review and create'];
const step = ref(0);
const name = ref('');
const tried = ref(false);
const policies = ref<string[]>([]);
const tags = ref<Tag[]>([]);

const columns: Column[] = [
  { id: 'name', header: 'User name', sortKey: 'name' },
  { id: 'path', header: 'Path', cell: () => '/' },
  { id: 'groups', header: 'Group', cell: () => '0' },
  { id: 'activity', header: 'Last activity', cell: () => '–' },
  { id: 'mfa', header: 'MFA', cell: () => '–' },
  { id: 'policies', header: 'Permissions policies', cell: r => String((r.policies || []).length) },
  { id: 'arn', header: 'ARN' },
  { id: 'created', header: 'Creation time', sortKey: 'created', cell: r => awsDate(r.created) },
];

const nameError = computed(() => {
  if (!name.value) return 'User name is required.';
  if (name.value.length > 64) return 'The user name can have up to 64 characters.';
  if (!/^[\w+=,.@-]+$/.test(name.value)) return 'Valid characters: A-Z, a-z, 0-9, and + = , . @ _ - (hyphen)';
  if (users.value.some(u => u.name.toLowerCase() === name.value.toLowerCase())) return 'A user with this name already exists.';
  return '';
});

function next() {
  tried.value = true;
  if (step.value === 0 && nameError.value) return;
  step.value += 1;
}
async function create() {
  busy.value = true;
  const made = await ctx.run(cli(['aws', 'iam', 'create-user'], { '--user-name': name.value, '--tags': tagWords(tags.value) }));
  if (!made.ok) { busy.value = false; return; }
  for (const arn of policies.value) {
    await ctx.run(cli(['aws', 'iam', 'attach-user-policy'], { '--user-name': name.value, '--policy-arn': arn }));
  }
  busy.value = false;
  ctx.api.notify('success', `User created successfully`, `You can view and download the user's password and email instructions for signing in to the AWS Management Console.`);
  ctx.to('iam', 'user', { name: name.value });
}
async function remove() {
  busy.value = true;
  let done = 0;
  for (const userName of selected.value) {
    const user = users.value.find(u => u.name === userName);
    for (const arn of user?.policies || []) {
      await ctx.run(cli(['aws', 'iam', 'detach-user-policy'], { '--user-name': userName, '--policy-arn': arn }));
    }
    const result = await ctx.run(cli(['aws', 'iam', 'delete-user'], { '--user-name': userName }));
    if (result.ok) done += 1;
  }
  busy.value = false;
  deleting.value = false;
  if (done) ctx.api.notify('success', `${done} user(s) deleted.`);
  selected.value = [];
}
</script>

<style scoped>
.iu__off { opacity: .55; cursor: default; }
.iu__p { margin: 0; }
</style>
